export const locationService = {
  getStates: async () => {
    try {
      const data = await apiService.getStates();
      if (Array.isArray(data) && data.length > 0) {
        return data;
      }
    } catch (err) {
      // Quiet fallback without throwing user-facing warnings
    }
    return FALLBACK_STATES;
  },

  getDistricts: async (state) => {
    if (!state) return [];
    try {
      const data = await apiService.getDistricts(state);
      if (Array.isArray(data) && data.length > 0) {
        return data;
      }
    } catch (err) {
      // Quiet fallback without throwing user-facing warnings
    }

    const key = (state || '').strip ? state.strip().toLowerCase() : String(state).toLowerCase();
    if (FALLBACK_DISTRICTS[key]) {
      return FALLBACK_DISTRICTS[key];
    }
    // Search partial match
    for (const [stKey, distList] of Object.entries(FALLBACK_DISTRICTS)) {
      if (key.includes(stKey) || stKey.includes(key)) {
        return distList;
      }
    }
    return ["Central District", "North District", "South District", "East District", "West District"];
  }
};
